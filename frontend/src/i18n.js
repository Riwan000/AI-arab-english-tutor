export function t(lang, key, params = {}) {
  const template = STRINGS[lang]?.[key] ?? STRINGS[DEFAULT_LANGUAGE][key] ?? key;
  return Object.entries(params).reduce(
    (str, [name, value]) => str.replaceAll(`{${name}}`, value),
    template
  );
}
